// Made from the file by a script; ThemeVectorsTest holds them to it.

/** A ready colour's table, light or dark; null for a name that is not one. */
internal fun readyColorScheme(name: String, dark: Boolean): ColorScheme? = when (name) {
    ReadyColours.MATCHA -> if (dark) MATCHA_DARK else MATCHA_LIGHT
    ReadyColours.PEACH -> if (dark) PEACH_DARK else PEACH_LIGHT
    ReadyColours.SKY -> if (dark) SKY_DARK else SKY_LIGHT
    else -> null
}

